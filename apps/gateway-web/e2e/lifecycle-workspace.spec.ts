for (const width of [390, 1440]) test(`lifecycle drafts, disclosures, review and save at ${width}px`, async ({ page, request }, testInfo) => {
  await page.setViewportSize({ width, height: 900 });
  await signInAdmin(page); await page.goto(route);
  const whole = page.locator('form').filter({ has: page.locator('#event-date') });
  await whole.getByLabel('Event', { exact: true }).selectOption('adopted');
  await whole.getByLabel('Effective date', { exact: true }).fill('1949-05-08');
  await whole.getByLabel(/Event note/).fill('Recorded with archival evidence');
  await whole.getByRole('button', { name: 'Upload new document', exact: true }).click();
  const optional = whole.getByText('Optional details', { exact: true });
  await optional.focus(); await optional.press('Enter');
  await whole.getByLabel('Citation key', { exact: true }).fill('Grundgesetz1949');
  await whole.getByText('Publication details', { exact: true }).click();
  await whole.getByLabel('Publisher', { exact: true }).fill('Parliamentary Council');
  await whole.getByText('Library note', { exact: true }).click();
  await whole.getByLabel('Description', { exact: true }).fill('Retained upload draft');
  await page.getByRole('tab', { name: 'History', exact: true }).click();
  await page.getByRole('tab', { name: 'Record event', exact: true }).focus(); await page.keyboard.press('Enter');
  await expect(whole.getByLabel('Publisher', { exact: true })).toHaveValue('Parliamentary Council');
  await page.getByRole('button', { name: 'Hide context pane', exact: true }).click();
  await expect(page.locator('#lifecycle-context')).toBeHidden();
  await page.getByRole('button', { name: 'Show context pane', exact: true }).click();
  await optional.click(); await optional.click();
  await expect(whole.getByLabel('Citation key', { exact: true })).toHaveValue('Grundgesetz1949');
  await whole.getByRole('button', { name: 'Cancel', exact: true }).click();
  await whole.getByRole('button', { name: 'Review details' }).click();
  const review = page.getByRole('dialog', { name: 'Review event', exact: true });
  await expect(review).toContainText('Recorded with archival evidence');
  await review.getByRole('button', { name: 'Back to details' }).click();
  await expect(whole.getByLabel(/Event note/)).toHaveValue('Recorded with archival evidence');
  await request.post(mock + '/__lifecycle_workspace', { data: { fail: true } });
  await whole.getByRole('button', { name: 'Review details' }).click();
  await review.getByRole('button', { name: 'Save event', exact: true }).click();
  await expect(whole.getByRole('alert')).toContainText('Your entries are preserved');
  await expect(whole.getByLabel(/Event note/)).toHaveValue('Recorded with archival evidence');
  await request.post(mock + '/__lifecycle_workspace', { data: { fail: false } });
  await whole.getByRole('button', { name: 'Review details' }).click();
  await review.getByRole('button', { name: 'Save event', exact: true }).click();
  await expect(page).toHaveURL(/saved=1/);
  await page.getByRole('tab', { name: 'History', exact: true }).click();
  await expect(page.getByRole('tabpanel')).toContainText('Recorded with archival evidence');
  expect((await request.get(mock + `/api/catalog/constitutions/${constitution}/lifecycle-events`).then(r => r.json())).length).toBe(1);
  await page.getByRole('tab', { name: 'Record event', exact: true }).click();
  await page.addScriptTag({ path: path.join(process.cwd(), 'node_modules/axe-core/axe.min.js') });
  expect(await page.evaluate(async () => (await (window as any).axe.run(document.body)).violations.map((item: any) => ({ id: item.id, targets: item.nodes.map((node: any) => node.target) })))).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('lifecycle-workspace.png'), fullPage: true });
});

test('exact provision selection survives tab changes and version cancellation', async ({ page, request }) => {
  await signInAdmin(page); await page.goto(route);
  await page.getByRole('radio', { name: /Selected provisions/ }).check();
  await page.getByRole('button', { name: 'Select provisions', exact: true }).click();
  const picker = page.getByRole('dialog', { name: 'Select provisions', exact: true });
  await picker.getByRole('searchbox').fill('1');
  await picker.getByRole('checkbox').first().check();
  await picker.getByRole('button', { name: 'Use selection' }).click();
  const provisions = page.locator('form').filter({ has: page.locator('#provision-event-date') });
  const previousVersion = await page.locator('#scope-version').inputValue();
  await page.locator('#scope-version').selectOption(VERSION_1949);
  await page.getByRole('dialog', { name: 'Change source version?' }).getByRole('button', { name: 'Cancel' }).click();
  await expect(page.locator('#scope-version')).toHaveValue(previousVersion);
  await provisions.getByLabel('Event', { exact: true }).selectOption('deferred');
  await provisions.getByLabel('Effective date', { exact: true }).fill('2030-01-01');
  await page.getByRole('tab', { name: 'History', exact: true }).click(); await page.keyboard.press('ArrowLeft');
  await expect(provisions.getByLabel('Effective date', { exact: true })).toHaveValue('2030-01-01');
  await provisions.getByRole('button', { name: 'Review details' }).click();
  await page.getByRole('dialog', { name: 'Review event', exact: true }).getByRole('button', { name: 'Save event', exact: true }).click();
  await expect(page).toHaveURL(/saved=1/);
  const events = await request.get(mock + `/api/catalog/constitutions/${constitution}/provision-events`).then(r => r.json());
  expect(events).toHaveLength(1); expect(events[0].logicalUnitIds).toHaveLength(1); expect(events[0].sourceVersionId).toBe(previousVersion);
});
