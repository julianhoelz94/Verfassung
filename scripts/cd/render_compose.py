#!/usr/bin/env python3
"""Generate the prebuilt-image Coolify definition from the canonical service wiring."""

import argparse
import copy
from pathlib import Path

import yaml

from release import image_paths, image_variable


def environment_map(value):
    if isinstance(value, dict):
        return value.copy()
    return dict(item.split("=", 1) for item in (value or []))


def render(root):
    root = Path(root)
    document = copy.deepcopy(yaml.safe_load((root / "docker-compose.yml").read_text()))
    # This host is backed up by the operator; do not start an application dump container.
    document["services"].pop("backup-service", None)
    images = image_paths(root)
    for name, service in document["services"].items():
        service.pop("ports", None)
        service.pop("container_name", None)
        service["restart"] = "unless-stopped"
        environment = environment_map(service.get("environment"))
        if "build" in service and name not in images:
            raise ValueError(f"Unpackaged source build: {name}")
        service.pop("build", None)
        if name in images:
            service["image"] = "${" + image_variable(name) + ":?Select an image using the manual deployment workflow}"
        for key, value in list(environment.items()):
            if isinstance(value, str):
                environment[key] = value.replace("${POSTGRES_PASSWORD:-postgres}", "${POSTGRES_PASSWORD:?Set a database password}")
        if "SPRING_PROFILES_ACTIVE" in environment:
            environment["SPRING_PROFILES_ACTIVE"] = "production"
            service["healthcheck"] = {
                "test": ["CMD", "bash", "-ec", "exec 3<>/dev/tcp/127.0.0.1/8080; printf 'GET /actuator/health HTTP/1.0\\r\\nHost: localhost\\r\\n\\r\\n' >&3; grep -q '\"status\":\"UP\"' <&3"],
                "interval": "15s", "timeout": "5s", "retries": 12, "start_period": "60s",
            }
        if name == "identity-service":
            environment = {key: value for key, value in environment.items()
                           if not key.startswith(("LOCAL_", "CI_", "TEST_", "IDENTITY_SEED_"))}
            environment.update({
                "IDENTITY_SEED_MODE": "off",
                "IDENTITY_MFA_ENCRYPTION_KEY": "${IDENTITY_MFA_ENCRYPTION_KEY:?Set the persistent encryption key}",
                "PROD_ADMIN_EMAIL": "${PROD_ADMIN_EMAIL:?Set the bootstrap admin email}",
                "PROD_ADMIN_PASSWORD": "${PROD_ADMIN_PASSWORD:?Set the bootstrap admin password}",
                "INGESTION_MANAGED_CREDENTIALS": "true",
            })
        if name in {"identity-service", "ingestion-service"}:
            for purpose in ("PUBLISH", "AUDIT", "SEARCH"):
                key = "INGESTION_" + purpose + "_TOKEN"
                environment[key] = "${" + key + ":?Deploy using the manual deployment workflow}"
        if name in {"gateway-web", "mcp-server", "identity-service", "edge-proxy"}:
            environment["PUBLIC_BASE_URL"] = "${PUBLIC_BASE_URL:?Set the public HTTPS origin}"
        if name in {"gateway-web", "edge-proxy", "identity-service"}:
            environment["TLS_MODE"] = "external-proxy"
        if name == "gateway-web":
            environment.update({"SESSION_COOKIE_SECURE": "true", "IDENTITY_SEED_MODE": "off",
                                "NEXT_PUBLIC_BASE_URL": "${PUBLIC_BASE_URL:?Set the public HTTPS origin}"})
        if name == "edge-proxy":
            environment.update({"PROFILE": "production", "CADDY_EXPOSE_API_DOCS": "false",
                                "CADDY_BIND_ADDRESS": "0.0.0.0",
                                "TLS_TRUSTED_PROXIES": "${TLS_TRUSTED_PROXIES:?Set the actual Coolify proxy CIDRs}"})
            environment.pop("ACME_TEST_DIRECTORY", None)
            service["expose"] = ["80"]
        if environment:
            service["environment"] = environment
    header = "# Generated by scripts/cd/render_compose.py; keep service wiring in docker-compose.yml.\n"
    return header + yaml.safe_dump(document, sort_keys=False, width=110)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path("docker-compose.coolify.yml")
    result = render(Path.cwd())
    if args.check:
        if path.read_text() != result:
            raise SystemExit("Regenerate docker-compose.coolify.yml with scripts/cd/render_compose.py")
    else:
        path.write_text(result)
